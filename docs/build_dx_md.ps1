$docsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$outputFile = Join-Path $docsDir "DX.md"

$files = Get-ChildItem -Path $docsDir -Filter "*.md" -Recurse |
    Where-Object { $_.Name -ne "DX.md" -and $_.Name -ne "README.md" -and $_.Directory.Name -ne "canary" } |
    Sort-Object FullName

$sb = [System.Text.StringBuilder]::new()

[void]$sb.AppendLine("# DX Ecosystem Documentation")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("This file is auto-generated by build_dx_md.ps1.")
[void]$sb.AppendLine("It connects all DX tool documentation pages into one file.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("---")
[void]$sb.AppendLine("")

foreach ($file in $files) {
    $toolName = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)
    [void]$sb.AppendLine("## $toolName")
    [void]$sb.AppendLine("")
    $content = Get-Content -Path $file.FullName -Raw
    [void]$sb.AppendLine($content)
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("---")
    [void]$sb.AppendLine("")
}

$output = $sb.ToString()
Set-Content -Path $outputFile -Value $output -Encoding UTF8

Write-Host "DX.md created at $outputFile"
Write-Host "Total tools included: $($files.Count)"